#!/usr/bin/env sh
# Tests tools/gen-third-party.sh against a fake vendor/ tree: the table and the
# per-module sections, the check mode, an unchanged hand-written part, and the
# refusal of a module without a license file.
set -eu
here=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
gen=$here/gen-third-party.sh
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT HUP INT TERM
fail() { echo "FAIL $1" >&2; exit 1; }
pass() { echo "PASS $1"; }

vendor=$work/vendor
mkdir -p "$vendor/example.net/alpha/sub" "$vendor/example.net/beta"
cat > "$vendor/modules.txt" <<'EOM'
# example.net/alpha v1.2.3
## explicit; go 1.20
example.net/alpha
example.net/alpha/sub
# example.net/beta v0.0.0-20240101000000-abcdef123456
## explicit; go 1.21
example.net/beta
EOM
printf 'Alpha license text  \r\nSecond line\n' > "$vendor/example.net/alpha/LICENSE"
printf 'Alpha notice\n' > "$vendor/example.net/alpha/NOTICE"
printf 'Beta license text\n' > "$vendor/example.net/beta/COPYING"

doc=$work/THIRD_PARTY.md
cat > "$doc" <<'EOM'
# Notices

Hand-written head.

<!-- BEGIN GO MODULES (generated by tools/gen-third-party.sh; do not edit) -->
stale content
<!-- END GO MODULES -->

Hand-written tail.
EOM

run() { VENDOR_DIR=$vendor OUT=$doc sh "$gen" "$@"; }

run --check >/dev/null 2>&1 && fail "check passed on stale content"
pass "check refuses a stale file"
run
grep -q '^| `example.net/alpha` | v1.2.3 | LICENSE, NOTICE |$' "$doc" || fail "table row for alpha"
grep -q '^| `example.net/beta` | v0.0.0-20240101000000-abcdef123456 | COPYING |$' "$doc" || fail "table row for beta"
grep -q '^Packages: example.net/alpha, example.net/alpha/sub$' "$doc" || fail "alpha packages"
grep -q '^Alpha license text$' "$doc" || fail "license text with CR and trailing space stripped"
grep -q '^Beta license text$' "$doc" || fail "beta text"
grep -q 'stale content' "$doc" && fail "old content kept"
grep -q '^Hand-written head\.$' "$doc" || fail "head kept"
grep -q '^Hand-written tail\.$' "$doc" || fail "tail kept"
grep -q ' $' "$doc" && fail "trailing whitespace in output"
pass "sections generated, hand-written parts kept"
run --check >/dev/null || fail "check failed on a fresh file"
pass "check accepts a fresh file"
cp "$doc" "$work/first"
run
cmp -s "$doc" "$work/first" || fail "second run changed the file"
pass "generation is idempotent"

# No vendor directory: the empty statement, still idempotent.
VENDOR_DIR=$work/none OUT=$doc sh "$gen"
grep -q 'links no third-party Go modules' "$doc" || fail "empty statement"
pass "no vendored modules"

# A module without a license file is refused.
mkdir -p "$vendor/example.net/gamma"
printf '# example.net/gamma v1.0.0\n## explicit; go 1.20\nexample.net/gamma\n' >> "$vendor/modules.txt"
cp "$work/first" "$doc"
if run >/dev/null 2>"$work/err"; then fail "module without a license accepted"; fi
grep -q 'no license file for example.net/gamma' "$work/err" || fail "refusal names the module"
cmp -s "$doc" "$work/first" || fail "failed run modified the file"
pass "module without a license file is refused"

# Missing markers are refused.
printf '# no markers\n' > "$doc"
if run >/dev/null 2>&1; then fail "file without markers accepted"; fi
pass "markers required"
echo "all gen-third-party tests passed"
