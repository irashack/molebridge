#!/usr/bin/env sh
# Regenerates the Go module section of THIRD_PARTY.md from vendor/modules.txt
# and the license files `go mod vendor` copied next to each module's packages.
# Everything outside the BEGIN/END markers is hand-written and left alone.
#
#   sh tools/gen-third-party.sh            rewrite THIRD_PARTY.md
#   sh tools/gen-third-party.sh --check    exit 1 if THIRD_PARTY.md is stale
#
# VENDOR_DIR and OUT override the defaults (used by the test). A vendored
# module without a license file is an error: add the notice by hand to the
# hand-written part and record why, then teach this script, rather than ship
# a module with no notice.
set -eu
LC_ALL=C
export LC_ALL
root=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)
vendor=${VENDOR_DIR:-$root/vendor}
out=${OUT:-$root/THIRD_PARTY.md}
mode='write'
case "${1:-}" in
    '') ;;
    --check) mode=check ;;
    *) echo "usage: gen-third-party.sh [--check]" >&2; exit 2 ;;
esac
begin='<!-- BEGIN GO MODULES (generated by tools/gen-third-party.sh; do not edit) -->'
end='<!-- END GO MODULES -->'
[ -f "$out" ] || { echo "gen-third-party: $out does not exist" >&2; exit 1; }
grep -qxF "$begin" "$out" && grep -qxF "$end" "$out" || {
    echo "gen-third-party: $out lacks the BEGIN/END markers" >&2
    exit 1
}
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT HUP INT TERM

# One "module version" line per vendored module; "=> replacement" lines of
# replaced modules keep the replacement's path (the files live under it).
modules=$work/modules
: > "$modules"
if [ -f "$vendor/modules.txt" ]; then
    awk '
        /^# / {
            path = $2; version = $3
            if (NF >= 5 && $4 == "=>") { path = $5; version = $6 }
            print path, version
        }' "$vendor/modules.txt" > "$modules"
fi

# License-like file names directly under a vendored module's directory.
license_files() {
    for f in "$1"/LICENSE* "$1"/LICENCE* "$1"/COPYING* "$1"/NOTICE* "$1"/PATENTS*; do
        [ -f "$f" ] && basename "$f"
    done
    return 0
}

body=$work/body
{
    if [ ! -s "$modules" ]; then
        echo "The binary links no third-party Go modules (the Go standard library"
        echo "is covered above)."
    else
        echo "Vendored under \`vendor/\`, linked into the \`molebridge\` binary. Each"
        echo "module's license text is reproduced as vendored."
        echo
        echo "| Module | Version | License file |"
        echo "|---|---|---|"
        while read -r path version; do
            files=$(license_files "$vendor/$path")
            [ -n "$files" ] || {
                echo "gen-third-party: no license file for $path in $vendor/$path" >&2
                exit 1
            }
            echo "| \`$path\` | $version | $(echo "$files" | tr '\n' ' ' | sed 's/ *$//; s/ /, /g') |"
        done < "$modules"
        while read -r path version; do
            echo
            echo "### $path $version"
            echo
            pkgs=$(awk -v mod="$path" '
                /^# / { cur = ($2 == mod || ($4 == "=>" && $5 == mod)); next }
                /^#/ { next }
                cur { print $1 }' "$vendor/modules.txt" | tr '\n' ' ' | sed 's/ *$//; s/ /, /g')
            echo "Packages: $pkgs"
            for f in $(license_files "$vendor/$path"); do
                echo
                echo "\`$f\`:"
                echo
                echo "~~~~text"
                tr -d '\r' < "$vendor/$path/$f" | sed 's/[[:space:]]*$//'
                echo "~~~~"
            done
        done < "$modules"
    fi
} > "$body"

new=$work/new
awk -v begin="$begin" -v end="$end" -v body="$body" '
    $0 == begin { print; print ""; while ((getline line < body) > 0) print line; print ""; skip = 1; next }
    $0 == end { skip = 0 }
    !skip { print }' "$out" > "$new"

if [ "$mode" = check ]; then
    if cmp -s "$new" "$out"; then
        echo "THIRD_PARTY.md is current"
    else
        echo "THIRD_PARTY.md is stale: run sh tools/gen-third-party.sh" >&2
        exit 1
    fi
else
    cat "$new" > "$out"
fi
