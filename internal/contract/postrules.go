package contract

import (
	"errors"
	"fmt"
	"strconv"
	"strings"
)

// What gluetun v3.41.3's chain parser accepts in a rule line
// (internal/firewall/list.go): targets at :314-321, protocols at :324-340,
// and after the in/out/source/destination columns only the optional fields at
// :243-279, which iptables prints for `-m tcp/udp --dport N` and `-m
// conntrack --ctstate S`.
var (
	gluetunTargets   = map[string]bool{"ACCEPT": true, "DROP": true, "REJECT": true, "REDIRECT": true}
	gluetunProtocols = map[string]bool{"all": true, "icmp": true, "tcp": true, "udp": true}
)

// PostRuleParseable is post_rule_parseable: true when an `-A <chain> ...`
// rule, once listed by iptables, is a line gluetun's chain parser accepts.
func PostRuleParseable(rule string) bool {
	tokens := strings.Fields(rule)
	if len(tokens) < 4 || tokens[0] != "-A" || tokens[len(tokens)-2] != "-j" || !gluetunTargets[tokens[len(tokens)-1]] {
		return false
	}
	i := 2
	var protocol, module string
	given := map[string]bool{}
	body := tokens[2 : len(tokens)-2]
	for i-2 < len(body) {
		option := tokens[i]
		if i+1 >= len(tokens)-2 {
			return false
		}
		value := tokens[i+1]
		switch {
		case option == "-i" || option == "-o" || option == "-s" || option == "-d":
		case option == "-p" && gluetunProtocols[value] && protocol == "":
			protocol = value
		case option == "-m" && (value == "tcp" || value == "udp" || value == "conntrack") && module == "":
			module = value
		case option == "--dport" && (module == "tcp" || module == "udp") && module == protocol && isASCIIDigits(value):
		case option == "--ctstate" && module == "conntrack":
		default:
			return false
		}
		given[option] = true
		i += 2
	}
	// A match module with nothing to print would leave a lone `udp` or `tcp`,
	// which gluetun's parser reads past the end of the line.
	if module == "" {
		return true
	}
	if module == "tcp" || module == "udp" {
		return given["--dport"]
	}
	return given["--ctstate"]
}

func isASCIIDigits(s string) bool { return isUint(s) }

// postRulesHeader is the comment block of the generated file. gluetun ignores
// every line that does not start with iptables or ip6tables.
var postRulesHeader = []string{
	"# Generated by molebridge gluetun-post-rules; regenerate instead of editing.",
	"# gluetun runs these after enabling its firewall. They are not Molebridge's guard,",
	"# which is policy routing (docs/architecture.md#gluetun-backend).",
}

// RenderPostRules is render_post_rules: gluetun's /iptables/post-rules.txt for
// the gluetun backend.
//
// gluetun v3.41.3 runs each line that starts with `iptables ` or `ip6tables `
// (or their -nft/-legacy names) once, after enabling its firewall, split on
// whitespace without a shell; any other line is ignored. A failing line
// disables the firewall and stops gluetun, and an ip6tables line fails when
// gluetun found no working ip6tables, so ipv6=false leaves those out for such
// a host.
//
// These accepts let the exit work under gluetun's DROP policies. They are not
// the guard: NetBird rewrites FORWARD, and policy routing holds the
// tunnel-only property.
//
// Every rule must also survive gluetun's own parser. To remove one of its
// rules, gluetun lists the whole chain with `iptables -L <chain>
// --line-numbers -n -v` and parses every line, ours included. A line it can't
// parse stops the removal, and its old accepts pile up. It accepts only the
// targets ACCEPT, DROP, REJECT and REDIRECT, so not a jump to a chain of our
// own, and after the address columns only `tcp dpt:N`, `udp dpt:N`, `redir
// ports N` and `ctstate S`, so no `-m mark`. PostRuleParseable checks that.
// The control mark therefore can't narrow the OUTPUT accept: it accepts
// everything leaving by HOST_IF, as gluetun's own `-o <tunnel> -j ACCEPT`
// does for the tunnel. Policy routing decides what leaves that way: NetBird's
// marked control traffic by rules 88/89, gluetun's WireGuard socket by rule
// 102, HOST_IF's subnets by 103; rule 104 stops the namespace's other
// unmarked traffic that gluetun's rule 101 didn't take; forwarded traffic
// never reaches OUTPUT.
func RenderPostRules(c Config, wireguardPort int, ipv6 bool) (string, error) {
	if !c.IsGluetun() {
		return "", errors.New("post-rules are for the gluetun backend")
	}
	if wireguardPort < 1 || wireguardPort > 65535 {
		return "", errors.New("the NetBird WireGuard port must be 1..65535")
	}
	for _, name := range []string{c.OverlayIf, c.ExitIf, c.HostIf} {
		if !ValidInterfaceName(name) {
			return "", errors.New("invalid interface name")
		}
	}
	overlay, tunnel, host := c.OverlayIf, c.ExitIf, c.HostIf
	rules := []string{
		fmt.Sprintf("-A FORWARD -i %s -o %s -j ACCEPT", overlay, tunnel),
		fmt.Sprintf("-A FORWARD -i %s -o %s -m conntrack --ctstate ESTABLISHED,RELATED -j ACCEPT", tunnel, overlay),
		fmt.Sprintf("-A OUTPUT -o %s -j ACCEPT", host),
		fmt.Sprintf("-A INPUT -i %s -p udp -m udp --dport %s -j ACCEPT", host, strconv.Itoa(wireguardPort)),
	}
	for _, r := range rules {
		if !PostRuleParseable(r) {
			return "", errors.New("a post-rule gluetun's chain parser would reject")
		}
	}
	lines := append([]string(nil), postRulesHeader...)
	for _, r := range rules {
		lines = append(lines, "iptables "+r)
	}
	if ipv6 {
		for _, r := range rules {
			lines = append(lines, "ip6tables "+r)
		}
	}
	return strings.Join(lines, "\n") + "\n", nil
}
