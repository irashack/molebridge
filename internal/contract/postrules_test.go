func TestPostRulesMatchGluetunsParser(t *testing.T) { // test_post_rules_match_gluetuns_parser
	text, err := RenderPostRules(gluetunConfig(), 51820, true)
	if err != nil {
		t.Fatal(err)
	}
	var lines []string
	for _, l := range strings.Split(text, "\n") {
		if strings.HasPrefix(l, "iptables ") || strings.HasPrefix(l, "ip6tables ") {
			lines = append(lines, l)
		}
	}
	if len(lines) != 8 {
		t.Fatalf("%d lines", len(lines))
	}
	have := map[string]bool{}
	for _, l := range lines {
		have[l] = true
	}
	for _, want := range []string{
		"iptables -A FORWARD -i wt0 -o wg0 -j ACCEPT",
		"ip6tables -A FORWARD -i wg0 -o wt0 -m conntrack --ctstate ESTABLISHED,RELATED -j ACCEPT",
		"iptables -A OUTPUT -o eth0 -j ACCEPT",
		"ip6tables -A INPUT -i eth0 -p udp -m udp --dport 51820 -j ACCEPT",
	} {
		if !have[want] {
			t.Errorf("missing %q", want)
		}
	}
	// gluetun ignores every other line, so comments are safe; nothing needs a shell.
	for _, l := range strings.Split(strings.TrimSuffix(text, "\n"), "\n") {
		if !have[l] && !strings.HasPrefix(l, "#") {
			t.Errorf("unexpected line %q", l)
		}
	}
	for _, l := range lines {
		if strings.ContainsAny(l, "\"'$`;|&") {
			t.Errorf("shell metacharacter in %q", l)
		}
	}
	cfg := gluetunConfig()
	cfg.ControlMark, cfg.HostIf = 0x2000, "enp3s0"
	v4, err := RenderPostRules(cfg, 40000, false)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(v4, "ip6tables") || !strings.Contains(v4, "-o enp3s0 ") || !strings.Contains(v4, "--dport 40000 ") {
		t.Errorf("%s", v4)
	}
	if strings.Contains(v4, "-m mark") || strings.Contains(text, "-m mark") {
		t.Error("a mark match would not survive gluetun's parser")
	}
	if !strings.HasSuffix(text, "\n") || !strings.HasPrefix(text, "# Generated by") {
		t.Error("layout")
	}
}

func TestEveryPostRuleSurvivesGluetunsChainParser(t *testing.T) { // test_every_post_rule_survives_gluetuns_chain_parser
	other := gluetunConfig()
	other.HostIf, other.ControlMark = "enp3s0", 0x2000
	for _, cfg := range []Config{gluetunConfig(), other} {
		text, _ := RenderPostRules(cfg, 51820, true)
		chains := map[string]bool{}
		n := 0
		for _, l := range strings.Split(text, "\n") {
			if !strings.HasPrefix(l, "iptables ") && !strings.HasPrefix(l, "ip6tables ") {
				continue
			}
			rule := strings.SplitN(l, " ", 2)[1]
			n++
			if !PostRuleParseable(rule) {
				t.Errorf("%q", rule)
			}
			chains[strings.Fields(rule)[1]] = true
		}
		if n == 0 || len(chains) != 3 || !chains["FORWARD"] || !chains["OUTPUT"] || !chains["INPUT"] {
			t.Errorf("%d %v", n, chains)
		}
	}
}

func TestPostRuleParseabilityFollowsGluetunsParser(t *testing.T) { // test_post_rule_parseability_follows_gluetuns_parser
	for rule, ok := range map[string]bool{
		"-A OUTPUT -o eth0 -j ACCEPT":                                                   true,
		"-A INPUT -i eth0 -p udp -m udp --dport 51820 -j ACCEPT":                        true,
		"-A FORWARD -i wg0 -o wt0 -m conntrack --ctstate ESTABLISHED,RELATED -j ACCEPT": true,
		"-A OUTPUT -d 198.51.100.1 -o eth0 -p udp -m udp --dport 51820 -j ACCEPT":       true,
		"-A OUTPUT -o eth0 -m mark --mark 0x1bd00 -j ACCEPT":                            false,
		"-A OUTPUT -o eth0 -j MOLEBRIDGE-OUT":                                           false,
		"-A OUTPUT -o eth0 -g MOLEBRIDGE-OUT":                                           false,
		"-A OUTPUT -o eth0 -m comment --comment x -j ACCEPT":                            false,
		"-A OUTPUT -o eth0 -p udp -m udp --sport 51820 -j ACCEPT":                       false,
		"-A OUTPUT -o eth0 -p tcp -m udp --dport 1 -j ACCEPT":                           false,
		"-A OUTPUT -o eth0 -m owner --uid-owner 0 -j ACCEPT":                            false,
		"-A OUTPUT -o eth0 -j LOG":                                                      false,
		"-I OUTPUT -o eth0 -j ACCEPT":                                                   false,
		"-A INPUT -i eth0 -p udp -m udp -j ACCEPT":                                      false,
		"-A INPUT -i eth0 -m conntrack -j ACCEPT":                                       false,
		"":                       false,
		"-A OUTPUT -j":           false,
		"-A OUTPUT -o -j ACCEPT": false,
	} {
		if got := PostRuleParseable(rule); got != ok {
			t.Errorf("%q: %v", rule, got)
		}
	}
}

func TestPostRulesRefuseBadPorts(t *testing.T) { // test_post_rules_refuse_bad_ports
	for _, port := range []int{0, 65536, -1} {
		if _, err := RenderPostRules(gluetunConfig(), port, true); err == nil {
			t.Errorf("%d accepted", port)
		}
	}
}

