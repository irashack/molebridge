func sentinelVariants() []string {
	// The sentinel as a field name, a bare line, every field's value, a
	// section header, inside a hook, and as a key that looks right.
	out := []string{
		strings.Replace(mullvad, "MTU = 1420", "MTU = 1420\n"+sentinel+" = x", 1),
		strings.Replace(mullvad, "MTU = 1420", "MTU = 1420\n"+sentinel, 1),
		strings.Replace(mullvad, "[Interface]", "["+sentinel+"]", 1),
		strings.Replace(mullvad, "table 51821; ip -6", "table 51821; "+sentinel+"; ip -6", 1),
	}
	for _, field := range []string{"PrivateKey", "Address", "MTU", "Table", "PostUp", "PreDown", "PublicKey", "Endpoint", "AllowedIPs", "PersistentKeepalive"} {
		lines := strings.Split(mullvad, "\n")
		for i, l := range lines {
			if strings.HasPrefix(l, field+" =") {
				lines[i] = field + " = " + sentinel
			}
		}
		out = append(out, strings.Join(lines, "\n"))
	}
	return out
}

func TestNoMessageCarriesConfText(t *testing.T) { // test_no_message_carries_conf_text
	for i, text := range sentinelVariants() {
		conf, msg := check(t, text, Mullvad)
		if conf != nil || msg == "" {
			t.Errorf("variant %d accepted", i)
		}
		if strings.Contains(msg, sentinel) || strings.Contains(msg, zeroKey) {
			t.Errorf("variant %d leaks: %q", i, msg)
		}
		_, err := Parse(text, Mullvad, table)
		if err == nil || strings.Contains(err.Error(), sentinel) {
			t.Errorf("variant %d: %v", i, err)
		}
	}
}

func TestUnreadableOrOddFilesAreRefused(t *testing.T) { // test_unreadable_or_odd_files_are_refused
	type fileCase struct {
		name  string
		setup func(dir string)
		want  string
	}
	write := func(dir, text string) { _ = os.WriteFile(filepath.Join(dir, "mullvad.conf"), []byte(text), 0o600) }
	cases := []fileCase{
		{"NUL", func(d string) { write(d, strings.Replace(mullvad, "MTU", "M\x00TU", 1)) }, "NUL or carriage-return bytes"},
		{"CR", func(d string) { write(d, strings.ReplaceAll(mullvad, "\n", "\r\n")) }, "NUL or carriage-return bytes"},
		{"large", func(d string) { write(d, mullvad+strings.Repeat("#", 5000)+"\n") }, "is larger than 4 KiB"},
		{"exactly 4 KiB of comments", func(d string) { write(d, mullvad+strings.Repeat("#", 4096-len(mullvad)-1)+"\n") }, ""},
		{"symlink", func(d string) {
			write(d, mullvad)
			_ = os.Rename(filepath.Join(d, "mullvad.conf"), filepath.Join(d, "real.conf"))
			_ = os.Symlink(filepath.Join(d, "real.conf"), filepath.Join(d, "mullvad.conf"))
		}, "is not a regular file"},
		{"directory", func(d string) { _ = os.Mkdir(filepath.Join(d, "mullvad.conf"), 0o700) }, "is not a regular file"},
		{"missing", func(d string) {
			write(d, mullvad)
			_ = os.Rename(filepath.Join(d, "mullvad.conf"), filepath.Join(d, "real.conf"))
		}, "mullvad.conf is missing; regenerate it with"},
	}
	for _, c := range cases {
		dir := t.TempDir()
		c.setup(dir)
		_, err := Load(dir, "mullvad", Mullvad, table)
		if c.want == "" {
			if err != nil {
				t.Errorf("%s: %v", c.name, err)
			}
			continue
		}
		if err == nil || !strings.Contains(strings.ReplaceAll(err.Error(), dir, "DIR"), c.want) {
			t.Errorf("%s: %v, want %q", c.name, err, c.want)
		}
	}
	if _, err := Load(t.TempDir()+"/absent", "mullvad", Mullvad, table); err == nil || !strings.Contains(err.Error(), "is missing; regenerate it with prepare-config (docs/setup.md)") {
		t.Errorf("a missing directory: %v", err)
	}
}

func TestUnreadableFile(t *testing.T) {
	if os.Geteuid() == 0 {
		t.Skip("root reads anything")
	}
	dir := t.TempDir()
	path := filepath.Join(dir, "mullvad.conf")
	if err := os.WriteFile(path, []byte(mullvad), 0o000); err != nil {
		t.Fatal(err)
	}
	_, err := Load(dir, "mullvad", Mullvad, table)
	if err == nil || !strings.Contains(err.Error(), "can't be read (on Docker the container needs DAC_READ_SEARCH; see docs/setup.md)") {
		t.Fatal(err)
	}
	if err := os.Chmod(dir, 0o000); err != nil {
		t.Fatal(err)
	}
	defer os.Chmod(dir, 0o700)
	_, err = Load(dir, "mullvad", Mullvad, table)
	if err == nil || !strings.Contains(err.Error(), "can't be searched") {
		t.Fatal(err)
	}
}

