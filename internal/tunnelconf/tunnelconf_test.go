// Fictitious values: all-zero keys and documentation addresses.
const (
	zeroKey  = "AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA="
	sentinel = "SENTINELq7Zk"
	table    = 51821
)

func mullvadConf(addresses string, keepalive bool) string {
	hasV6 := strings.Contains(addresses, ":")
	post := "ip route replace default dev %i table 51821"
	pre := "ip route del default dev %i table 51821"
	allowed := "0.0.0.0/0"
	if hasV6 {
		post += "; ip -6 route replace default dev %i table 51821"
		pre += "; ip -6 route del default dev %i table 51821"
		allowed += ", ::/0"
	}
	lines := []string{
		"# Generated by tools/prepare-tunnel-config.py. Keep mode 0600; never commit.",
		"[Interface]",
		"PrivateKey = " + zeroKey,
		"Address = " + addresses,
		"MTU = 1420",
		"Table = off",
		"PostUp = " + post,
		"PreDown = " + pre,
		"",
		"[Peer]",
		"PublicKey = " + zeroKey,
		"Endpoint = 198.51.100.10:51820",
		"AllowedIPs = " + allowed,
	}
	if keepalive {
		lines = append(lines, "PersistentKeepalive = 25")
	}
	return strings.Join(append(lines, ""), "\n")
}

var (
	mullvad  = mullvadConf("203.0.113.2/32, 2001:db8:3::2/128", true)
	mullvad4 = mullvadConf("203.0.113.2/32", true)
	piaConf  = strings.Join([]string{
		"# Generated by tools/prepare-tunnel-config.py --pia. Keep mode 0600; never commit.",
		"# No tunnel address or peer: the applier sets both when it registers this key with PIA.",
		"[Interface]", "PrivateKey = " + zeroKey, "MTU = 1420", "Table = off",
		"PostUp = ip route replace default dev %i table 51821", "PreDown = ip route del default dev %i table 51821", ""}, "\n")
	nordvpnConf = strings.Join([]string{
		"# Generated by tools/nordvpn-key.py. Keep mode 0600; never commit.",
		"# No peer: the applier sets it when a server is chosen.",
		"[Interface]", "PrivateKey = " + zeroKey, "Address = 10.5.0.2/32", "MTU = 1420", "Table = off",
		"PostUp = ip route replace default dev %i table 51821", "PreDown = ip route del default dev %i table 51821", ""}, "\n")
)

func check(t *testing.T, text string, provider Provider) (*Conf, string) {
	t.Helper()
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, string(provider)+".conf"), []byte(text), 0o600); err != nil {
		t.Fatal(err)
	}
	c, err := Load(dir, string(provider), provider, table)
	if err != nil {
		return nil, strings.ReplaceAll(err.Error(), dir, "DIR")
	}
	return c, ""
}

func TestGeneratedConfigsAreAccepted(t *testing.T) { // test_generated_configs_are_accepted
	for name, c := range map[string]struct {
		provider Provider
		text     string
		families string
	}{
		"mullvad dual stack": {Mullvad, mullvad, "an IPv4 address and an IPv6 address"},
		"mullvad IPv4":       {Mullvad, mullvad4, "an IPv4 address"},
		"pia":                {PIA, piaConf, "no address (the applier sets it)"},
		"nordvpn":            {NordVPN, nordvpnConf, "an IPv4 address"},
	} {
		conf, msg := check(t, c.text, c.provider)
		if conf == nil {
			t.Errorf("%s: %s", name, msg)
			continue
		}
		if conf.Families() != c.families {
			t.Errorf("%s: %q", name, conf.Families())
		}
		if strings.Contains(fmt.Sprintf("%v %+v %#v %s", conf, conf, conf, conf), "AAAAAAAA") {
			t.Errorf("%s: the key is printable", name)
		}
	}
}

func TestParsedValues(t *testing.T) {
	c, msg := check(t, mullvad, Mullvad)
	if c == nil {
		t.Fatal(msg)
	}
	if c.Addr4 != netip.MustParseAddr("203.0.113.2") || c.Addr6 != netip.MustParseAddr("2001:db8:3::2") || c.MTU != 1420 || c.Table != table {
		t.Errorf("%v %v %d", c.Addr4, c.Addr6, c.MTU)
	}
	if c.Peer == nil || c.Peer.Endpoint != netip.MustParseAddrPort("198.51.100.10:51820") || c.Peer.Keepalive != 25 ||
		len(c.Peer.AllowedIPs) != 2 || c.RuleOwner() != "conf" {
		t.Errorf("%+v", c.Peer)
	}
	if c.PrivateKey != [32]byte{} || c.Peer.PublicKey != [32]byte{} {
		t.Error("the all-zero key should decode to zero bytes")
	}
	up, down := c.UpRoutes(), c.DownRoutes()
	if len(up) != 2 || !up[0].Replace || up[0].Family != rtnl.V4 || up[1].Family != rtnl.V6 || up[0].Table != table || down[0].Replace {
		t.Errorf("%+v %+v", up, down)
	}
	c, _ = check(t, mullvad4, Mullvad)
	if len(c.UpRoutes()) != 1 || c.Addr6.IsValid() || len(c.Peer.AllowedIPs) != 1 {
		t.Errorf("IPv4 only: %+v", c)
	}
	// Keepalive is optional.
	c, msg = check(t, mullvadConf("203.0.113.2/32", false), Mullvad)
	if c == nil || c.Peer.Keepalive != 0 {
		t.Errorf("%v %s", c, msg)
	}
	c, _ = check(t, piaConf, PIA)
	if c.RuleOwner() != "applier" || c.Peer != nil || len(c.UpRoutes()) != 1 || c.Addr4.IsValid() {
		t.Errorf("PIA: %+v", c)
	}
	c, _ = check(t, nordvpnConf, NordVPN)
	if c.Addr4 != netip.MustParseAddr("10.5.0.2") || c.Peer != nil || c.RuleOwner() != "conf" {
		t.Errorf("NordVPN: %+v", c)
	}
}

